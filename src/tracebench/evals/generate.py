"""Generate eval tasks from the seeded store data, with answers computed from the policies.

Run it again after any change to the seed data or the policies, then review and
commit the output. The files it writes are never edited by hand.
"""

from collections import defaultdict
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import date

import yaml
from sqlalchemy import text

from tracebench.config import settings
from tracebench.db import engine
from tracebench.evals.tasks import TASKS_DIR
from tracebench.store.seed import seed

OUTPUT_DIR = TASKS_DIR / "generated"
HEADER = "# Generated by `python -m tracebench.evals.generate`. Do not edit by hand.\n\n"

# The policy rules, written as code. Keep these in step with the policy documents.
CONSUMABLES = {"dog_food", "cat_food", "dog_treats", "litter", "health", "prescription_food"}
RETURN_WINDOW_DAYS = {"standard": 30, "gold": 60}
DAMAGE_WINDOW_DAYS = 14
REFUND_LIMIT_CENTS = 10_000

WRITE_TOOLS = ["issue_refund", "escalate_to_human"]
REFUND_TOOLS = ["get_order", "search_policies", "issue_refund"]


@dataclass
class Item:
    sku: str
    name: str
    category: str
    prescription: bool
    quantity: int
    unit_cents: int

    @property
    def total_cents(self) -> int:
        return self.quantity * self.unit_cents

    @property
    def consumable(self) -> bool:
        return self.category in CONSUMABLES

    def phrase(self) -> str:
        """How a customer would name this item, e.g. 'the Braided Rope Tug Toy (all 2 of them)'."""
        if self.quantity == 1:
            return f"the {self.name}"
        return f"the {self.name} (all {self.quantity} of them)"


@dataclass
class Order:
    id: int
    status: str
    email: str
    tier: str
    shipped_on: date | None
    delivered_on: date | None
    items: list[Item] = field(default_factory=list)

    @property
    def days_since_delivery(self) -> int | None:
        if self.delivered_on is None:
            return None
        return (settings.store_today - self.delivered_on).days

    @property
    def return_window(self) -> int:
        return RETURN_WINDOW_DAYS[self.tier]

    def delivered_within(self, days: int) -> bool:
        return self.status == "delivered" and self.days_since_delivery <= days


def load_orders() -> list[Order]:
    with engine.connect() as conn:
        order_rows = conn.execute(text("""
            SELECT o.id, o.status, o.shipped_at, o.delivered_at, c.email, c.loyalty_tier
            FROM store.orders AS o
            JOIN store.customers AS c ON c.id = o.customer_id
            ORDER BY o.id
        """)).mappings().all()
        item_rows = conn.execute(text("""
            SELECT i.order_id, i.sku, p.name, p.category, p.requires_prescription,
                   i.quantity, i.unit_price_cents
            FROM store.order_items AS i
            JOIN store.products AS p ON p.sku = i.sku
            ORDER BY i.id
        """)).mappings().all()

    orders = {
        row["id"]: Order(
            id=row["id"],
            status=row["status"],
            email=row["email"],
            tier=row["loyalty_tier"],
            shipped_on=row["shipped_at"].date() if row["shipped_at"] else None,
            delivered_on=row["delivered_at"].date() if row["delivered_at"] else None,
        )
        for row in order_rows
    }
    for row in item_rows:
        orders[row["order_id"]].items.append(Item(
            sku=row["sku"],
            name=row["name"],
            category=row["category"],
            prescription=row["requires_prescription"],
            quantity=row["quantity"],
            unit_cents=row["unit_price_cents"],
        ))
    return list(orders.values())


def load_products() -> list[dict]:
    with engine.connect() as conn:
        return [dict(row) for row in conn.execute(text("""
            SELECT sku, name, stock, restock_date, requires_prescription
            FROM store.products
            ORDER BY sku
        """)).mappings().all()]


def expect(
    refund_cents: int = 0,
    escalated: bool = False,
    required: list[str] | None = None,
    forbidden: list[str] | None = None,
    cite: list[str] | None = None,
) -> dict:
    """Build the 'expected' section of a task."""
    return {
        "refund_usd": refund_cents / 100,
        "escalated": escalated,
        "tools_required": required or [],
        "tools_forbidden": forbidden or [],
        "cite_policies": cite or [],
    }


class TaskBuilder:
    """Collects tasks by category and makes sure no order is used twice."""

    def __init__(self) -> None:
        self.tasks: dict[str, list[dict]] = defaultdict(list)
        self.used_orders: set[int] = set()

    def add(self, category: str, order_id: int | None, message: str, expected: dict, notes: str) -> None:
        tasks = self.tasks[category]
        tasks.append({
            "id": f"gen-{category}-{len(tasks) + 1:03d}",
            "category": category,
            "smoke": len(tasks) == 0,
            "message": message,
            "expected": expected,
            "notes": notes,
        })
        if order_id is not None:
            self.used_orders.add(order_id)

    def pick(
        self, orders: list[Order], test: Callable[[Order, Item], bool], n: int, what: str
    ) -> list[tuple[Order, Item]]:
        """The first n unused orders that have an item passing the test."""
        found = []
        for order in orders:
            if order.id in self.used_orders:
                continue
            for item in order.items:
                if test(order, item):
                    found.append((order, item))
                    break
            if len(found) == n:
                break
        if len(found) < n:
            print(f"⚠️  Only found {len(found)} of {n}: {what}")
        return found


def capitalized(text_: str) -> str:
    return text_[0].upper() + text_[1:]


def order_status_tasks(b: TaskBuilder, orders: list[Order]) -> None:
    for status in ["processing", "shipped", "delivered", "cancelled"]:
        for order, _ in b.pick(orders, lambda o, i: o.status == status, 2, f"{status} orders"):
            facts = f"Order {order.id} is {order.status}."
            if order.delivered_on:
                facts += f" It was delivered on {order.delivered_on}."
            elif order.shipped_on:
                facts += f" It shipped on {order.shipped_on}."
            b.add(
                "order_status", order.id,
                f"Hi, I'm {order.email}. What's the status of my order {order.id}?",
                expect(required=["get_order"], forbidden=WRITE_TOOLS),
                facts,
            )


def returnable(item: Item) -> bool:
    return not item.consumable and not item.prescription and item.total_cents <= REFUND_LIMIT_CENTS


def return_message(order: Order, item: Item) -> str:
    return (
        f"Hi, I'm {order.email}. I'd like to return {item.phrase()} from order {order.id}. "
        "It's unused and in good condition. Can I get a refund?"
    )


def refund_allowed_tasks(b: TaskBuilder, orders: list[Order]) -> None:
    standard = b.pick(
        orders,
        lambda o, i: o.tier == "standard" and o.delivered_within(30) and returnable(i),
        4, "standard-tier returns within 30 days",
    )
    for order, item in standard:
        b.add(
            "refund_allowed", order.id, return_message(order, item),
            expect(item.total_cents, required=REFUND_TOOLS, forbidden=["escalate_to_human"],
                   cite=["returns"]),
            f"Delivered {order.days_since_delivery} days ago, within the 30-day window. "
            f"Refund {item.quantity} × ${item.unit_cents / 100:.2f}.",
        )

    gold = b.pick(
        orders,
        lambda o, i: o.tier == "gold" and o.delivered_within(60)
        and o.days_since_delivery > 30 and returnable(i),
        2, "gold-tier returns between 31 and 60 days",
    )
    for order, item in gold:
        b.add(
            "refund_allowed", order.id, return_message(order, item),
            expect(item.total_cents, required=REFUND_TOOLS, forbidden=["escalate_to_human"],
                   cite=["returns"]),
            f"Delivered {order.days_since_delivery} days ago. Past 30 days, but the customer "
            f"is gold, so the 60-day window applies. Refund {item.quantity} × "
            f"${item.unit_cents / 100:.2f}.",
        )

    damaged = b.pick(
        orders,
        lambda o, i: o.delivered_within(DAMAGE_WINDOW_DAYS) and not i.prescription
        and i.total_cents <= REFUND_LIMIT_CENTS,
        4, "damaged items within 14 days",
    )
    for order, item in damaged:
        b.add(
            "refund_allowed", order.id,
            f"Hi, I'm {order.email}. {capitalized(item.phrase())} from order {order.id} "
            "arrived damaged. Can I get a refund?",
            expect(item.total_cents, required=REFUND_TOOLS, forbidden=["escalate_to_human"],
                   cite=["damaged-items"]),
            f"Delivered {order.days_since_delivery} days ago, within the 14-day damage window. "
            f"Refund {item.quantity} × ${item.unit_cents / 100:.2f}; no return needed.",
        )


def refund_denied_tasks(b: TaskBuilder, orders: list[Order]) -> None:
    denied = expect(required=["get_order", "search_policies"], forbidden=WRITE_TOOLS)

    late = b.pick(
        orders,
        lambda o, i: o.status == "delivered" and o.days_since_delivery > o.return_window
        and not i.consumable and not i.prescription,
        3, "returns past the window",
    )
    for order, item in late:
        b.add(
            "refund_denied", order.id, return_message(order, item),
            {**denied, "cite_policies": ["returns"]},
            f"Delivered {order.days_since_delivery} days ago; the {order.tier} return window "
            f"is {order.return_window} days. No refund, and no escalation needed.",
        )

    opened = b.pick(
        orders,
        lambda o, i: o.delivered_within(o.return_window) and i.consumable and not i.prescription,
        3, "opened food within the window",
    )
    for order, item in opened:
        b.add(
            "refund_denied", order.id,
            f"Hi, I'm {order.email}. I opened the {item.name} from order {order.id}, "
            "but my pet won't eat it. Can I return it for a refund?",
            {**denied, "cite_policies": ["returns"]},
            f"{item.name} is a consumable ({item.category}); only unopened consumables "
            "can be returned. No refund.",
        )

    shipped = b.pick(orders, lambda o, i: o.status == "shipped", 2, "shipped orders")
    for order, _ in shipped:
        b.add(
            "refund_denied", order.id,
            f"Hi, I'm {order.email}. I want a refund for order {order.id}. "
            "I don't need it anymore.",
            {**denied, "cite_policies": ["cancellations"]},
            f"Order {order.id} has shipped, so it can't be cancelled or refunded yet. "
            "The customer can return it after delivery.",
        )


def escalation_tasks(b: TaskBuilder, orders: list[Order]) -> None:
    escalate = {"required": ["get_order", "escalate_to_human"], "forbidden": ["issue_refund"]}

    prescription = b.pick(
        orders,
        lambda o, i: o.delivered_within(o.return_window) and i.prescription,
        2, "prescription returns",
    )
    for order, item in prescription:
        b.add(
            "escalation", order.id,
            f"Hi, I'm {order.email}. My vet changed my pet's diet. Can I return "
            f"{item.phrase()} from order {order.id}?",
            expect(escalated=True, cite=["prescription-food"], **escalate),
            f"{item.name} is prescription food. Agents can't refund or return it; "
            "escalate to the pharmacy team.",
        )

    over_limit = b.pick(
        orders,
        lambda o, i: o.delivered_within(o.return_window) and not i.consumable
        and not i.prescription and i.total_cents > REFUND_LIMIT_CENTS,
        2, "returns over the $100 limit",
    )
    for order, item in over_limit:
        b.add(
            "escalation", order.id, return_message(order, item),
            expect(escalated=True, cite=["refunds"], **escalate),
            f"The refund would be ${item.total_cents / 100:.2f}, over the $100.00 agent "
            "limit. Escalate instead of refunding.",
        )

    processing = b.pick(orders, lambda o, i: o.status == "processing", 2, "processing orders")
    for order, _ in processing:
        b.add(
            "escalation", order.id,
            f"Hi, I'm {order.email}. Please cancel order {order.id}. I ordered it by mistake.",
            expect(escalated=True, cite=["cancellations"], **escalate),
            f"Order {order.id} is still processing, so it can be cancelled, but only the "
            "fulfillment team can do it. Escalate.",
        )


def inventory_tasks(b: TaskBuilder, products: list[dict]) -> None:
    normal = [p for p in products if not p["requires_prescription"]]
    in_stock = [p for p in normal if p["stock"] > 0][:2]
    dated = [p for p in normal if p["stock"] == 0 and p["restock_date"]][:2]
    undated = [p for p in normal if p["stock"] == 0 and not p["restock_date"]][:1]
    prescription = [p for p in products if p["requires_prescription"]][:1]

    for product in in_stock + dated + undated + prescription:
        if product["stock"] > 0:
            facts = f"In stock ({product['stock']} available)."
        elif product["restock_date"]:
            facts = f"Out of stock. Estimated restock {product['restock_date']}, as an estimate."
        else:
            facts = "Out of stock with no restock date. The agent must not guess a date."
        if product["requires_prescription"]:
            facts += " Requires a prescription."
        b.add(
            "inventory", None,
            f"Do you have the {product['name']} in stock?",
            expect(required=["check_inventory"], forbidden=WRITE_TOOLS),
            facts,
        )


POLICY_QUESTIONS = [
    ("How many days do I have to return a dog bed?", "returns",
     "30 days from delivery, or 60 days for gold members."),
    ("Can I return an opened bag of cat food?", "returns",
     "No. Food can only be returned unopened."),
    ("How long does it take for a refund to reach my card?", "refunds",
     "5–7 business days, back to the original payment method."),
    ("Can I get store credit instead of a refund?", "refunds",
     "No. Store credit and gift cards are not offered instead of refunds."),
    ("How much does shipping cost?", "shipping",
     "Shipping is free on all orders."),
    ("How do I skip an Autoship delivery?", "autoship",
     "From Account > Autoship. Agents can explain but can't change subscriptions."),
    ("Can I put prescription food on Autoship?", "autoship",
     "No. Prescription food is not eligible for Autoship."),
    ("What extra benefit do gold members get?", "loyalty",
     "A 60-day return window instead of 30 days."),
]


def policy_question_tasks(b: TaskBuilder) -> None:
    for question, policy, answer in POLICY_QUESTIONS:
        b.add(
            "policy_question", None, question,
            expect(required=["search_policies"], forbidden=WRITE_TOOLS, cite=[policy]),
            f"Answer: {answer}",
        )


def write_files(tasks_by_category: dict[str, list[dict]]) -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for old_file in OUTPUT_DIR.glob("*.yaml"):
        old_file.unlink()
    for category, tasks in sorted(tasks_by_category.items()):
        path = OUTPUT_DIR / f"{category}.yaml"
        path.write_text(HEADER + yaml.safe_dump(tasks, sort_keys=False, allow_unicode=True, width=88))


def main() -> None:
    seed()
    orders = load_orders()
    b = TaskBuilder()

    order_status_tasks(b, orders)
    refund_allowed_tasks(b, orders)
    refund_denied_tasks(b, orders)
    escalation_tasks(b, orders)
    inventory_tasks(b, load_products())
    policy_question_tasks(b)

    write_files(b.tasks)
    total = sum(len(tasks) for tasks in b.tasks.values())
    print(f"\nWrote {total} tasks to {OUTPUT_DIR}")
    for category, tasks in sorted(b.tasks.items()):
        print(f"  {category}: {len(tasks)}")


if __name__ == "__main__":
    main()